import { expect, test } from '@playwright/test'
import { axe } from './helpers'

/** Change password-by-default: a readable passcode is the default, opting out is an informed choice. */
test.describe('passcode by default', () => {
  test('creation proposes a readable passcode right under the title, in simple mode', async ({ page }) => {
    await page.goto('/new')
    await page.getByTestId('mode-simple').click()
    const field = page.getByTestId('setup-passcode')
    await expect(field).toHaveValue(/^[A-Za-z0-9]{6}-[A-Za-z0-9]{6}-[A-Za-z0-9]{6}$/)
    // Right under the title: the passcode block comes before the format step.
    const title = await page.getByTestId('setup-title').boundingBox()
    const pass = await page.getByTestId('passcode-block').boundingBox()
    const format = await page.getByTestId('tab-all').boundingBox()
    expect(pass!.y).toBeGreaterThan(title!.y)
    expect(pass!.y).toBeLessThan(format!.y)
    const first = await field.inputValue()
    await page.getByTestId('passcode-regen').click()
    expect(await field.inputValue()).not.toBe(first)
    await expect(page.getByTestId('passcode-generator')).toHaveCount(0)
    const found = (await axe(page).include('[data-testid="passcode-block"]').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze()).violations.map((v) => v.id)
    expect(found).toEqual([])
  })

  test('the generated passcode protects the board: a participant is asked for it', async ({ page, browser }) => {
    await page.goto('/new')
    await page.getByTestId('tab-all').click()
    await page.getByTestId('template-start-stop-continue').click()
    const code = await page.getByTestId('setup-passcode').inputValue()
    await page.getByTestId('setup-submit').click()
    await page.getByTestId('name-input').fill('Alice')
    await page.getByTestId('name-save').click()
    await expect(page.getByTestId('share-passcode-value')).toHaveValue(code)
    const url = await page.getByTestId('share-url').inputValue()
    const bob = await (await browser.newContext()).newPage()
    await bob.goto(url)
    await expect(bob.getByTestId('passcode-input')).toBeVisible()
    await bob.getByTestId('passcode-input').fill(code)
    await bob.getByTestId('passcode-submit').click()
    await bob.getByTestId('name-input').fill('Bob')
    await bob.getByTestId('name-save').click()
    await expect(bob.getByTestId('board')).toBeVisible()
  })

  test('clearing the passcode asks for confirmation that lists the risks; cancel keeps it', async ({ page }) => {
    await page.goto('/new')
    const field = page.getByTestId('setup-passcode')
    await field.fill('')
    await expect(page.getByTestId('passcode-strength')).toContainText(/Pas de mot de passe|No passcode/)
    await page.getByTestId('setup-submit').click()
    const dialog = page.getByRole('dialog')
    await expect(dialog).toContainText(/lire et écrire|read and write/)
    await page.getByRole('button', { name: /Annuler|Cancel/ }).click()
    await expect(page).toHaveURL(/\/new/)
    // Create anyway.
    await page.getByTestId('setup-submit').click()
    await page.getByTestId('confirm').click()
    await page.getByTestId('name-input').fill('Alice')
    await page.getByTestId('name-save').click()
    await expect(page.getByTestId('board')).toBeVisible()
    await expect(page.getByTestId('share-passcode-value')).toHaveCount(0)
  })

  test('advanced mode has a full generator: length, classes, look-alikes, passphrase', async ({ page }) => {
    await page.goto('/new')
    await page.getByTestId('mode-advanced').click()
    await page.getByTestId('passcode-generator').locator('summary').click()
    await page.getByTestId('passcode-style-random').click()
    const field = page.getByTestId('setup-passcode')
    await expect(field).toHaveValue(/^[A-Za-z0-9]{20}$/)
    await page.getByTestId('passcode-class-symbols').check()
    await page.getByTestId('passcode-class-digits').uncheck()
    const v = await field.inputValue()
    expect(v).toMatch(/[^A-Za-z0-9]/)
    expect(v).not.toMatch(/[0-9]/)
    expect(v).not.toMatch(/[O0oIl1|B8S5Z2]/)
    await page.getByTestId('passcode-length').fill('40')
    await expect(field).toHaveValue(/^.{40}$/)
    await page.getByTestId('passcode-style-passphrase').click()
    await page.getByTestId('passcode-words').fill('6')
    await expect(field).toHaveValue(/^([a-z]{6}-){5}[a-z]{6}$/)
    await expect(page.getByTestId('passcode-strength')).toContainText(/Fort|Strong/)
    await page.getByTestId('passcode-reveal').click()
    await expect(field).toHaveAttribute('type', 'password')
    const found = (await axe(page).include('[data-testid="passcode-block"]').withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa', 'wcag22aa']).analyze()).violations.map((v) => `${v.id}: ${v.nodes.map((n) => n.html.slice(0, 120)).join(' | ')}`)
    expect(found).toEqual([])
  })

  test('the creator reloads and a returning participant comes back without being asked again', async ({ page, browser }) => {
    await page.goto('/new')
    await page.getByTestId('tab-all').click()
    await page.getByTestId('template-start-stop-continue').click()
    const code = await page.getByTestId('setup-passcode').inputValue()
    await page.getByTestId('setup-submit').click()
    await page.getByTestId('name-input').fill('Alice')
    await page.getByTestId('name-save').click()
    await expect(page.getByTestId('board')).toBeVisible()
    const url = await page.getByTestId('share-url').inputValue()
    await page.keyboard.press('Escape')
    // The creator reloads: the board reopens, no passcode prompt.
    await page.reload()
    await expect(page.getByTestId('board')).toBeVisible()
    await expect(page.getByTestId('passcode-input')).toHaveCount(0)

    const ctx = await browser.newContext()
    const bob = await ctx.newPage()
    await bob.goto(url)
    await bob.getByTestId('passcode-input').fill(code)
    await bob.getByTestId('passcode-submit').click()
    await bob.getByTestId('name-input').fill('Bob')
    await bob.getByTestId('name-save').click()
    await expect(bob.getByTestId('board')).toBeVisible()
    await bob.reload()
    await expect(bob.getByTestId('board')).toBeVisible()
    await expect(bob.getByTestId('passcode-input')).toHaveCount(0)
    // Nothing readable is stored: the passcode is sealed in the vault.
    const stored = await bob.evaluate(() => new Promise<string>((resolve) => {
      const open = indexedDB.open('retroboard-vault')
      open.onsuccess = () => {
        const all = open.result.transaction('codes').objectStore('codes').getAll()
        all.onsuccess = () => resolve(JSON.stringify(all.result, (_k, v) => (v instanceof ArrayBuffer ? Array.from(new Uint8Array(v)) : v)))
      }
    }))
    expect(stored.length).toBeGreaterThan(20)
    expect(stored).not.toContain(code)
  })
})
