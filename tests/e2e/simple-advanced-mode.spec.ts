test('landing: pasting a board link joins it, a wrong text says so (change join-by-link)', async ({ page, browser }) => {
  await page.goto('/new')
  await page.getByTestId('setup-title').fill('Join me')
  await page.getByTestId('tab-all').click()
  await page.getByTestId('template-halloween').click()
  await page.getByTestId('setup-passcode').fill('')
  await page.getByTestId('setup-submit').click()
  await page.getByTestId('confirm').click()
  await enterName(page, 'Alice')
  await expect(page.getByTestId('share-url')).toBeVisible()
  const link = await page.getByTestId('share-url').inputValue()

  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } })
  const bob = await ctx.newPage()
  await bob.goto('/')
  await bob.getByTestId('join-input').fill('hello')
  await bob.getByTestId('join-go').click()
  await expect(bob.getByTestId('join-error')).toBeVisible()
  await bob.getByTestId('join-input').fill(link)
  await bob.getByTestId('join-go').click()
  await enterName(bob, 'Bob')
  await expect(bob.getByTestId('board')).toBeVisible()
  await ctx.close()
})

