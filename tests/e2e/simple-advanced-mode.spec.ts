test('advanced options list every column with its voting switch', async ({ page }) => {
  await createBoard(page, { template: 'start-stop-continue', name: 'Alice' })
  await page.getByTestId('btn-options').click()
  const list = page.getByTestId('opt-votable-columns')
  await expect(list.locator('input[type=checkbox]')).toHaveCount(3)
  const first = list.locator('input[type=checkbox]').first()
  await first.uncheck()
  await expect(first).not.toBeChecked()
  await first.check()
})

test('voting can be turned off at creation: no voting bar, no vote buttons, and the options bring it back (change toast-notifications-v2)', async ({ page }) => {
  await page.goto('/new')
  await page.getByTestId('mode-advanced').click()
  await page.getByTestId('setup-title').fill('No votes')
  await page.getByTestId('setup-voting-enabled').uncheck()
  await page.getByTestId('setup-submit').click()
  await enterName(page, 'Alice')
  await expect(page.getByTestId('share-url')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('board')).toBeVisible()
  await expect(page.getByTestId('votebar')).toHaveCount(0)
  await page.getByTestId('btn-options').click()
  await expect(page.getByTestId('opt-voting-enabled')).not.toBeChecked()
  await page.getByTestId('opt-voting-enabled').check()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('votebar')).toBeVisible()
})
