import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'
import { createBoard, join, noteByText, publishNote } from './helpers'

test('write and publish without the mouse; typing a shortcut letter in a note does nothing', async ({ page }) => {
  await createBoard(page, { template: 'start-stop-continue' })
  await page.locator('body').click({ position: { x: 5, y: 300 } })
  await page.keyboard.press('2')
  await page.keyboard.press('n')
  const area = page.locator('section[data-anchor-kind="column"]').nth(1).locator('textarea')
  await expect(area).toBeFocused()
  await page.keyboard.type('plan pour 2 pompes')
  await expect(area).toHaveValue('plan pour 2 pompes')
  await expect(page.locator('article.note')).toHaveCount(0)
  await page.keyboard.press('Enter')
  await page.keyboard.press('Escape')
  await expect(area).not.toBeFocused()
  await page.keyboard.press('p')
  await expect(noteByText(page, 'plan pour 2 pompes')).toBeVisible()
  await expect(page.locator('section[data-anchor-kind="column"]').nth(1).locator('article.note')).toHaveCount(1)
})

test('arrows move between notes and columns, Enter edits, v votes, c opens the palette', async ({ page }) => {
  await createBoard(page, { template: 'start-stop-continue' })
  await publishNote(page, 0, 'Première')
  await publishNote(page, 0, 'Seconde')
  await publishNote(page, 1, 'Autre colonne')
  await page.locator('body').click({ position: { x: 5, y: 300 } })

  await page.keyboard.press('1')
  const first = page.locator('article.note').first()
  await expect(first).toBeFocused()
  expect(await first.evaluate((el) => getComputedStyle(el).outlineStyle)).not.toBe('none')
  await page.keyboard.press('ArrowDown')
  await expect(page.locator('section[data-anchor-kind="column"]').first().locator('article.note').nth(1)).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(noteByText(page, 'Autre colonne')).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('v')
  await expect.poll(() => page.locator('article.note:focus').getAttribute('data-testid')).toBeTruthy()

  await page.keyboard.press('c')
  await expect(page.getByTestId('palette')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('palette')).toBeHidden()

  await page.keyboard.press('1')
  await expect(page.locator('article.note').first()).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('article.note textarea')).toBeVisible()
  await page.keyboard.press('Escape')
})

test('facilitator keys drive the phase; participants of a one-facilitator board do not get them', async ({ page, browser }) => {
  await createBoard(page, { template: 'start-stop-continue', name: 'Alice', oneFacilitator: true })
  await page.getByTestId('btn-share').click()
  const link = await page.getByTestId('share-url').inputValue()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.locator('body').click({ position: { x: 5, y: 300 } })
  await page.keyboard.press(' ')
  await expect(page.getByTestId('agenda-phase')).toHaveText('Inclusion')
  await page.keyboard.press(']')
  await expect(page.getByTestId('agenda-phase')).not.toHaveText('Inclusion')
  await page.keyboard.press('[')
  await expect(page.getByTestId('agenda-phase')).toHaveText('Inclusion')

  const bob = await join(browser, link, 'Bob')
  await bob.page.locator('body').click({ position: { x: 5, y: 300 } })
  await bob.page.keyboard.press(']')
  await expect(bob.page.getByTestId('agenda-phase')).toHaveText('Inclusion')
})

test('? opens the help overlay (axe clean); the profile switch turns shortcuts off', async ({ page }) => {
  await createBoard(page)
  await page.locator('body').click({ position: { x: 5, y: 300 } })
  await page.keyboard.press('?')
  await expect(page.getByRole('dialog', { name: /Raccourcis clavier/ })).toBeVisible()
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()
  expect(result.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical').map((v) => v.id)).toEqual([])
  await page.keyboard.press('Escape')

  await page.getByTestId('btn-profile').click()
  await page.getByTestId('set-shortcuts').uncheck()
  await page.keyboard.press('Escape')
  await page.locator('body').click({ position: { x: 5, y: 300 } })
  await page.keyboard.press('n')
  await expect(page.locator('textarea:focus')).toHaveCount(0)
  await page.keyboard.press('?')
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
